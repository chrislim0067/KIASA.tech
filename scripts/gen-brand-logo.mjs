/**
 * Generates the 3D wordmark geometry for the hero logo.
 *
 * The original W is not text — it is ten hand-written 2D points extruded
 * (`buildWLogo` in index.html). There is no font in that scene, so swapping the
 * letter means supplying new outlines. This converts real glyphs into the same
 * kind of outline data at build time, so the runtime stays plain three.js with
 * no font loading and no extra network request.
 *
 *   node scripts/gen-brand-logo.mjs [TEXT]
 *
 * Output: public/brand/wordmark.js  (ES module, imported by the patched hero)
 */
import fs from 'node:fs';
import path from 'node:path';
import opentype from 'opentype.js';
import * as THREE from 'three';

const ROOT = path.resolve(import.meta.dirname, '..');
const TEXT = process.argv[2] ?? process.env.BRAND_TEXT ?? 'KIASA';
const FONT = path.join(ROOT, 'build-assets', 'Syncopate-Bold.ttf');
const OUT = path.join(ROOT, 'public', 'brand', 'wordmark.js');

/** Width in world units the wordmark is normalised to. The W spanned 4.8. */
const TARGET_WIDTH = Number(process.env.BRAND_WIDTH ?? 10.5);

// loadSync is deprecated in opentype 1.3+; parse the buffer directly.
const font = opentype.parse(fs.readFileSync(FONT).buffer);

// Syncopate is very widely spaced already; letterSpacing 0 keeps the metric
// spacing the typeface ships with, which is what the nav wordmark uses.
const otPath = font.getPath(TEXT, 0, 0, 100);

/* opentype's Y grows downward, three's grows upward — negate as we go. */
const cmds = [];
for (const c of otPath.commands) {
  if (c.type === 'M') cmds.push({ t: 'M', x: c.x, y: -c.y });
  else if (c.type === 'L') cmds.push({ t: 'L', x: c.x, y: -c.y });
  else if (c.type === 'Q') cmds.push({ t: 'Q', x1: c.x1, y1: -c.y1, x: c.x, y: -c.y });
  else if (c.type === 'C') cmds.push({ t: 'C', x1: c.x1, y1: -c.y1, x2: c.x2, y2: -c.y2, x: c.x, y: -c.y });
  else if (c.type === 'Z') cmds.push({ t: 'Z' });
}

/* Normalise: centre on the origin, scale to TARGET_WIDTH. */
let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for (const c of cmds) {
  for (const [px, py] of [[c.x, c.y], [c.x1, c.y1], [c.x2, c.y2]]) {
    if (px === undefined) continue;
    minX = Math.min(minX, px); maxX = Math.max(maxX, px);
    minY = Math.min(minY, py); maxY = Math.max(maxY, py);
  }
}
const scale = TARGET_WIDTH / (maxX - minX);
const cx = (minX + maxX) / 2;
const cy = (minY + maxY) / 2;
const fix = (v) => Number(((v - 0) * scale).toFixed(4));
for (const c of cmds) {
  if (c.x !== undefined) { c.x = fix(c.x - cx); c.y = fix(c.y - cy); }
  if (c.x1 !== undefined) { c.x1 = fix(c.x1 - cx); c.y1 = fix(c.y1 - cy); }
  if (c.x2 !== undefined) { c.x2 = fix(c.x2 - cx); c.y2 = fix(c.y2 - cy); }
}
const width = (maxX - minX) * scale;
const height = (maxY - minY) * scale;

/* Validate here rather than in the browser: build the shapes with the same
   three version the page uses and assert the counters came out as holes. */
function toShapes(isCCW) {
  const sp = new THREE.ShapePath();
  for (const c of cmds) {
    if (c.t === 'M') sp.moveTo(c.x, c.y);
    else if (c.t === 'L') sp.lineTo(c.x, c.y);
    else if (c.t === 'Q') sp.quadraticCurveTo(c.x1, c.y1, c.x, c.y);
    else if (c.t === 'C') sp.bezierCurveTo(c.x1, c.y1, c.x2, c.y2, c.x, c.y);
  }
  return sp.toShapes(isCCW);
}

const counterLetters = (TEXT.match(/[ABDOPQR]/g) ?? []).length;
let isCCW = false;
let shapes = toShapes(false);
let holes = shapes.reduce((n, s) => n + s.holes.length, 0);
if (holes !== counterLetters) {
  const alt = toShapes(true);
  const altHoles = alt.reduce((n, s) => n + s.holes.length, 0);
  if (Math.abs(altHoles - counterLetters) < Math.abs(holes - counterLetters)) {
    isCCW = true; shapes = alt; holes = altHoles;
  }
}

if (shapes.length === 0) throw new Error('no shapes produced — font or text is wrong');
if (holes !== counterLetters) {
  console.warn(`WARNING: expected ${counterLetters} counter(s) for "${TEXT}", got ${holes}. Letters may render filled.`);
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-brand-logo.mjs — do not edit by hand.
// "${TEXT}" in Syncopate Bold, converted to outline commands and normalised to
// ${width.toFixed(2)} x ${height.toFixed(2)} world units, centred on the origin.
export const WORDMARK_TEXT = ${JSON.stringify(TEXT)};
export const WORDMARK_SIZE = { width: ${width.toFixed(4)}, height: ${height.toFixed(4)} };
const IS_CCW = ${isCCW};
const CMD = ${JSON.stringify(cmds)};

/** Rebuilds the outlines as THREE.Shape instances (counters become holes). */
export function buildWordmarkShapes(THREE) {
  const p = new THREE.ShapePath();
  for (const c of CMD) {
    if (c.t === 'M') p.moveTo(c.x, c.y);
    else if (c.t === 'L') p.lineTo(c.x, c.y);
    else if (c.t === 'Q') p.quadraticCurveTo(c.x1, c.y1, c.x, c.y);
    else if (c.t === 'C') p.bezierCurveTo(c.x1, c.y1, c.x2, c.y2, c.x, c.y);
  }
  return p.toShapes(IS_CCW);
}
`
);

console.log(`text="${TEXT}"  shapes=${shapes.length}  holes=${holes} (expected ${counterLetters})  isCCW=${isCCW}`);
console.log(`size: ${width.toFixed(2)} x ${height.toFixed(2)} world units  (the W was 4.80 x 4.00)`);
console.log(`wrote ${path.relative(ROOT, OUT)}`);
